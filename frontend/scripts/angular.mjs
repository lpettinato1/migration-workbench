import {spawn} from 'node:child_process';
import {existsSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {resolve,dirname} from 'node:path';
const frontend=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const sdk=resolve(frontend,'node_modules/node/bin',process.platform==='win32'?'node.exe':'node');
const executable=existsSync(sdk)?sdk:process.execPath;
const cli=resolve(frontend,'node_modules/@angular/cli/bin/ng.js');
const child=spawn(executable,[cli,...process.argv.slice(2)],{cwd:frontend,stdio:'inherit',env:process.env});
child.on('error',error=>{console.error(error.message);process.exitCode=1;});
child.on('exit',code=>{process.exitCode=code??1;});
